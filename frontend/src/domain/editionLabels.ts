/**
 * 저작에 붙은 이름표를 화면에 적는 한 줄. 없으면 `null` 입니다.
 *
 * <p>이름표에는 두 가지가 섞여 옵니다. 한 저작으로 묶인 판본의 표기(「특별판」「양장」)와,
 * **표제에서는 보이지 않게 된 각색 표기**(「큰글자책」)입니다. 뒤엣것이 이 줄이 있어야 하는
 * 이유입니다. 정보나루가 「이방인 :큰글자책」으로 준 판은 그 말이 부제로 갈려 나가 표제가
 * 「이방인」만 남고, 저작은 보통 판과 따로 서므로 **표제·저자·출판사가 똑같은 줄이 둘**
 * 나갑니다. 실제로 민음사 「이방인」이 그랬습니다(2026-11-10).
 *
 * <p>**표제에 붙여 그리지 마세요.** 표제는 도서관의 제목 검색 주소에 그대로 들어가는
 * 값이라(`libraryLink` 의 `title`) 서버가 일부러 떼어서 줍니다. 화면에서 다시 붙여 하나의
 * 문자열로 들고 다니면 언젠가 그 문자열이 링크로 넘어갑니다.
 *
 * <p>**한 권 검색과 여러 권 검색이 이 함수를 함께 씁니다.** 한쪽에서만 그리면 같은 책이 한
 * 화면에서는 구별되고 다른 화면에서는 구별되지 않습니다. 여러 권 검색의 후보가 그랬습니다.
 */
export function editionLine(labels: readonly string[] | null | undefined): string | null {
  const shown = (labels ?? []).map((label) => label.trim()).filter(Boolean);
  return shown.length === 0 ? null : `판본 ${shown.join(' · ')}`;
}
