import type { ShelfBook } from '../api';

/**
 * 표지가 없는 책의 <b>대체 표지 바탕</b>.
 *
 * <h2>색을 분류번호가 정합니다</h2>
 *
 * <p>같은 갈래의 책들이 비슷한 색을 띠게 되는데, 실제 서가에서 한 출판사의 총서가
 * 같은 장정으로 늘어서 있는 것과 같은 모양입니다. 무작위로 칠하면 서가가 알록달록해져
 * 눈이 쉴 곳이 없고, <b>새로 고칠 때마다 색이 달라져 같은 책이 다른 책으로
 * 보입니다.</b> 분류번호로 정하면 몇 번을 열어도 같습니다.
 *
 * <h2>한 곳에 둡니다</h2>
 *
 * <p>서가와 「이 책 주변 서가」가 같은 책을 그립니다. 색 규칙이 갈리면 <b>녹색 책을
 * 눌렀는데 갈색 책이 나옵니다.</b> 누른 것과 열린 것이 같은 책인지 알 수 없어지는데,
 * 그 둘 사이에는 애니메이션도 없어서 잘못 눌렀다고 읽기 쉽습니다.
 */
export function coverPaper(book: ShelfBook): string {
  /*
    분류번호가 없으면 ISBN 이라도 씁니다. 이 색은 뜻을 담지 않고 갈래만 나누므로,
    색이 없는 것보다 아무 색이나 같은 규칙으로 정해지는 편이 낫습니다.
  */
  const digits = (book.call ?? book.isbn ?? '').replace(/[^0-9]/g, '');
  const hue = (Number(digits.slice(0, 3) || '0') * 37) % 360;

  // 채도와 밝기를 좁게 묶어 둡니다. 이 값을 넓히면 서가가 알록달록해집니다.
  return `linear-gradient(160deg,
    hsl(${hue} 22% 42%) 0%,
    hsl(${hue} 26% 32%) 55%,
    hsl(${hue} 24% 27%) 100%)`;
}
