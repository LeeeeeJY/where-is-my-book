import { describe, expect, it } from 'vitest';
import { olderAsOf } from '../asOf';

/**
 * 여러 책의 소장 정보를 한 문구로 묶어 말할 때 어느 날짜를 쓸 것인가.
 *
 * <p>캐시가 생기면서 책마다 받은 시점이 달라졌습니다. 마지막에 도착한 답으로 덮어쓰면
 * 한 달 전 값이 섞인 목록이 오늘 조회한 것처럼 보입니다.
 */
describe('olderAsOf', () => {
  it('더 오래된 쪽을 남긴다', () => {
    expect(olderAsOf('2026-09-08', '2026-08-01')).toBe('2026-08-01');
    expect(olderAsOf('2026-08-01', '2026-09-08')).toBe('2026-08-01');
  });

  it('한쪽이 없으면 있는 쪽을 쓴다', () => {
    // 물어보지 못한 책이 있다고 해서 나머지의 조회 시각까지 지울 이유는 없습니다.
    expect(olderAsOf(null, '2026-09-08')).toBe('2026-09-08');
    expect(olderAsOf('2026-09-08', null)).toBe('2026-09-08');
  });

  it('둘 다 없으면 없다', () => {
    // 여기서 오늘 날짜를 만들어 내면 안 됩니다. 물어보지 못한 것을 방금 확인한 것으로
    // 바꾸는 셈이라, 화면에 남은 「없습니다」가 오늘의 사실로 읽힙니다.
    expect(olderAsOf(null, null)).toBeNull();
  });

  it('해가 바뀌어도 순서가 맞는다', () => {
    expect(olderAsOf('2027-01-01', '2026-12-31')).toBe('2026-12-31');
  });
});
