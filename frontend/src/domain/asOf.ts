/**
 * 소장 정보의 「조회 기준」 날짜를 다루는 곳.
 *
 * <p>**같은 판단을 화면마다 따로 적지 않습니다.** 소장 상태(`holdingState.ts`), 대출
 * 문구(`loanStatus.ts`), 링크 단계(`opacLink.ts`) 를 한 곳에 모아 둔 것과 같은 이유입니다.
 * 화면이 늘 때 한쪽이 빠뜨리면, 옛 답이 새 답처럼 보이는데 아무도 눈치채지 못합니다.
 */

/**
 * 둘 중 **더 오래된** 날짜.
 *
 * <p>가장 최근이 아니라 가장 오래된 것을 남깁니다. 목록의 답은 책마다 받은 시점이 다른데,
 * 캐시에서 나온 것과 방금 받은 것이 섞이기 때문입니다. 그중 하나라도 오래된 값이 있으면
 * 그 목록 전체가 그만큼 오래된 것입니다. **최근 날짜를 말하면 실제보다 새것처럼 보이고,
 * 사용자는 「없습니다」를 오늘 확인한 사실로 읽습니다.**
 *
 * <p>둘 다 없으면 없습니다. 여기서 오늘 날짜를 만들어 내면 안 됩니다.
 */
export function olderAsOf(a: string | null, b: string | null): string | null {
  if (!a) return b;
  if (!b) return a;
  return a < b ? a : b; // ISO 날짜라 문자열 비교로 충분합니다.
}
