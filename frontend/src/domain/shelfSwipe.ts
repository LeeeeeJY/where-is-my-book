/**
 * 「이 책 주변 서가」에서 <b>손가락으로 옆으로 넘기는</b> 규칙.
 *
 * <h2>넘기는 자리는 서가입니다</h2>
 *
 * <p>이 화면은 서가 앞에 선 모습이라 좌우로 넘기는 것이 곧 옆으로 걸어가는 것인데,
 * <b>화면 전체를 넘기는 자리로 두면 하단 시트에서 손가락을 조금만 움직여도 책이
 * 넘어갑니다.</b> 시트는 지금 보고 있는 <b>그 한 권</b>에 관한 것을 담은 자리라,
 * 거기서 표제를 훑거나 청구기호를 짚는 동안 밑의 책이 바뀌면 방금 읽던 것이 무엇이었는지
 * 알 수 없어집니다. 머리 줄도 마찬가지입니다. 「책 찾기」 칸에 적은 것을 고치려고
 * 손가락을 끌면 그때마다 책이 넘어갑니다.
 *
 * <p>그래서 <b>손가락을 어디에 댔는지로 가릅니다.</b> 서가(라벨·책·선반과 그 둘레의
 * 어두운 자리)에서 시작한 것만 넘기는 것이고, 시트와 머리 줄에서 시작한 것은 아무리
 * 멀리 끌어도 넘기지 않습니다. <b>끝난 자리로 가르지 마세요.</b> 서가에서 시작해 시트
 * 위에서 손을 뗀 것은 넘긴 것이 맞고, 사람은 그것을 한 손짓으로 여깁니다.
 */

/**
 * 누른 것과 넘긴 것을 가르는 거리(px).
 *
 * <p>짧은 움직임은 넘긴 것이 아니라 누른 것입니다. 손가락은 가만히 누른다고 해도
 * 몇 픽셀씩 흔들립니다.
 */
export const SWIPE_MIN_PX = 40;

/**
 * 여기서 시작한 손가락은 <b>넘기는 것이 아닙니다.</b>
 *
 * <p>하단 시트(`.nearby__sheet`)와 머리 줄(`.nearby__bar`)입니다. 둘 다 읽고 누르고
 * 적는 자리라, 그 안에서의 손놀림은 책을 넘기라는 뜻이 아닙니다.
 */
export const NOT_SWIPE_FROM = '.nearby__sheet, .nearby__bar';

/**
 * 이 손놀림이 <b>몇 걸음인지.</b> 0이면 넘긴 것이 아닙니다.
 *
 * <p>왼쪽으로 끌면 다음 책(+1)입니다. 서가 앞에서 책을 왼쪽으로 밀어 내면 오른쪽 책이
 * 따라 들어오는 것과 같습니다.
 *
 * @param from 손가락을 댄 자리. <b>`null` 은 「넘기는 자리가 아니다」는 뜻입니다.</b>
 * @param to 손가락을 뗀 자리. 손이 화면 밖에서 떨어지면 없을 수 있습니다
 */
export function swipeStep(from: number | null, to: number | undefined): -1 | 0 | 1 {
  if (from === null || to === undefined) return 0;
  const moved = to - from;
  if (Math.abs(moved) < SWIPE_MIN_PX) return 0;
  return moved < 0 ? 1 : -1;
}
