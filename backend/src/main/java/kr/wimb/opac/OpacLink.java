package kr.wimb.opac;

/**
 * 도서관으로 넘길 링크와, 그 링크가 어느 단계인지.
 *
 * <p><b>단계를 함께 들고 다니는 것이 핵심입니다.</b> 상세 페이지로 못 보내고 홈페이지로
 * 내려앉았을 때 그것을 조용히 감추면, 사용자는 「소장하고 있다더니 홈페이지만 나오네」로
 * 읽고 검색 결과 자체를 의심하게 됩니다. 어느 단계인지 밝히면 「이 도서관은 아직 규칙을
 * 못 넣었구나」로 읽힙니다.
 */
public record OpacLink(String url, Kind kind) {

    /** 위에 있을수록 좋은 링크입니다. 이 순서대로 내려가며 고릅니다. */
    public enum Kind {
        /** 그 책의 상세 페이지. 주소에 ISBN 이 그대로 들어가 미리 만들 수 있는 경우입니다 */
        ISBN_DETAIL,
        /**
         * 그 책의 상세 페이지를 <b>누를 때 찾아서</b> 보냅니다. 상세 주소가 도서관 내부 키를
         * 써서 미리 만들 수 없는 OPAC 이 대부분이라, ISBN 검색 결과를 서버가 받아 그 안의
         * 상세 링크를 뽑습니다({@code DetailResolver}). 규칙 표에 적는 종류가 아니라 ISBN
         * 검색 규칙과 상세 패턴({@code detail-patterns.csv})이 함께 있을 때 저절로 됩니다.
         * <b>못 찾으면 검색 결과로 내려가므로</b> 화면은 그 가능성을 함께 말해야 합니다.
         */
        DETAIL_LOOKUP,
        /** ISBN 으로 검색한 결과. 한 건만 나오므로 사실상 상세와 가깝습니다 */
        ISBN_SEARCH,
        /** 제목으로 검색한 결과. 동명이서가 섞일 수 있습니다 */
        TITLE_SEARCH,
        /** 도서관 첫 화면. 규칙을 아직 못 넣은 도서관입니다 */
        HOMEPAGE
    }
}
