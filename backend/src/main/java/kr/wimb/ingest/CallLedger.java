package kr.wimb.ingest;

/**
 * 외부 API 를 그날 몇 번 불렀는지 적는 원장. <b>세기만 하고 막지 않습니다.</b>
 *
 * <p>예전에는 이 원장이 호출을 막았습니다. 하루 예산(25,000건)에 닿으면 부르지 않았고,
 * 배경 작업은 그 80% 에서 먼저 멈췄습니다. 둘 다 없앴습니다(2026-11-12).
 *
 * <ul>
 *   <li>정보나루의 하루 한도는 30,000건이고 그 한도까지 전부 씁니다. 우리 쪽에서 먼저
 *       멈추는 선은 쓰지 못하는 몫만 만들었습니다.</li>
 *   <li>도서관 목록 받기가 배경 등급이라, 80% 를 넘긴 날 서버가 새로 뜨면 목록을 받지
 *       못했습니다. 목록이 없으면 화면은 아무것도 고를 수 없습니다.</li>
 *   <li>한도를 넘겼을 때 믿는 것은 정보나루가 주는 오류({@code outOflimit})입니다.
 *       {@code Data4LibraryClient} 가 그 오류를 받으면 5분간 부르지 않고, 화면은 그것을
 *       「미소장」이 아니라 「확인 불가」로 그립니다.</li>
 * </ul>
 *
 * <p>남은 쓰임은 둘입니다. {@code /api/status} 와 {@code /api/diagnose} 가 그날 쓴 건수를
 * 말하고, 서가를 세우는 쪽({@code ShelfService})이 남은 건수를 보고 시작할지 정합니다.
 *
 * <p><b>이 원장을 거치지 않는 호출 경로를 만들지 마세요.</b> 한 곳이라도 새면 원장이
 * 실제로 쓴 건수와 어긋나고, 서가를 세울지 정하는 근거가 틀어집니다.
 */
public interface CallLedger {

    /** 호출 한 번을 적습니다. 실제로 요청을 내보내기 직전에 부릅니다. */
    void record(String sourceCode);

    /** 오늘(한국 날짜) 적은 건수. */
    int used(String sourceCode);

    /**
     * 그 소스의 하루 한도에서 오늘 쓴 건수를 뺀 값. 한도를 넘겨도 음수가 되지 않습니다.
     * 한도를 모르는 소스는 {@link Integer#MAX_VALUE} 입니다.
     */
    int remaining(String sourceCode);
}
