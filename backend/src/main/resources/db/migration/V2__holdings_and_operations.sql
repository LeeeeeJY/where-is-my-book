CREATE TABLE api_budget (
    source_code text    NOT NULL,
    usage_date  date    NOT NULL,
    call_count  integer NOT NULL DEFAULT 0,
    PRIMARY KEY (source_code, usage_date)
);

COMMENT ON TABLE api_budget IS
    '일일 한도를 코드에서 지키는 원장. 재시작해도 유지되어야 하므로 DB 에 둡니다. '
    '한도의 80%% 에 도달하면 배경 갱신을 멈추고, 사람이 기다리는 요청을 우선합니다.';
COMMENT ON COLUMN api_budget.usage_date IS
    'Asia/Seoul 기준 날짜입니다. 저장은 UTC 로 하되 이 경계만은 한국 시각 개념입니다.';

-- ---------------------------------------------------------------
-- 적재 이력
-- ---------------------------------------------------------------

CREATE TABLE ingest_run (
    run_id        bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_code   text        NOT NULL,
    scope_key     text,
    source_version text,
    mode          text        NOT NULL
                              CHECK (mode IN ('FULL_SNAPSHOT', 'INCREMENTAL', 'BACKFILL')),
    status        text        NOT NULL
                              CHECK (status IN ('RUNNING', 'SUCCEEDED', 'FAILED', 'PARTIAL', 'SKIPPED')),
    started_at    timestamptz NOT NULL DEFAULT now(),
    finished_at   timestamptz,
    input_uri     text,
    input_sha256  text,
    rows_read     bigint,
    rows_ok       bigint,
    rows_rejected bigint,
    archive_key   text,
    error_class   text,
    error_message text
);

COMMENT ON COLUMN ingest_run.scope_key IS
    '재시도 가능한 최소 단위를 가리킵니다. 서지 백필이면 발행일 구간, 벌크면 도서관부호입니다.';

-- 같은 응답을 다시 적재하는 것이 자동으로 건너뛰기가 됩니다.
-- 파일이나 응답을 다시 받는 일은 반드시 생기므로 이 제약이 실질적인 안전장치입니다.
CREATE UNIQUE INDEX ingest_run_idempotency_idx
    ON ingest_run (source_code, coalesce(scope_key, ''), input_sha256)
    WHERE input_sha256 IS NOT NULL;

CREATE INDEX ingest_run_scope_idx ON ingest_run (source_code, scope_key, started_at DESC);
CREATE INDEX ingest_run_status_idx ON ingest_run (status) WHERE status <> 'SUCCEEDED';

-- 변환할 수 없는 레코드는 예외를 던지지 않고 여기에 건수로 남깁니다.
-- 한 줄의 형식이 이상하다고 그 구간 전체의 적재가 중단되면 안 됩니다.
CREATE TABLE ingest_reject (
    run_id      bigint      NOT NULL REFERENCES ingest_run ON DELETE CASCADE,
    line_no     integer,
    raw_line    text,
    reason_code text        NOT NULL,
    detail      text,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ingest_reject_run_idx ON ingest_reject (run_id);

