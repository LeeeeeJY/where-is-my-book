CREATE TABLE opac_template (
    family_code       text    PRIMARY KEY,
    url_pattern       text    NOT NULL,
    query_kind        text    NOT NULL
                              CHECK (query_kind IN ('ISBN', 'TITLE', 'TITLE_AUTHOR')),
    encoding          text    NOT NULL DEFAULT 'UTF-8',
    no_result_markers text[]  NOT NULL DEFAULT '{}',
    ok_markers        text[]  NOT NULL DEFAULT '{}',
    notes             text
);

COMMENT ON COLUMN opac_template.encoding IS
    '국내 OPAC 중에는 한글 질의를 EUC-KR 로 퍼센트 인코딩해야 하는 곳이 아직 있습니다. '
    'UTF-8 로 보내면 HTTP 200 이 오면서 결과만 0건이 되는데, 조용히 실패하는 가장 나쁜 형태입니다.';
COMMENT ON COLUMN opac_template.no_result_markers IS
    '국내 OPAC 은 결과가 없어도 대부분 200 을 반환합니다. 상태 코드만 보는 점검은 '
    '아무것도 검증하지 못하므로 본문에서 이 문구를 찾습니다.';

CREATE TABLE library_opac (
    lib_code             varchar(20) PRIMARY KEY REFERENCES library ON DELETE CASCADE,
    family_code          text        REFERENCES opac_template,
    base_url             text        NOT NULL,
    vars                 jsonb       NOT NULL DEFAULT '{}',
    detail_url_pattern   text,
    fallback_url         text        NOT NULL,
    status               text        NOT NULL DEFAULT 'UNKNOWN'
                                     CHECK (status IN ('UNKNOWN', 'OK', 'BROKEN', 'BLOCKED', 'UNVERIFIABLE')),
    last_checked_at      timestamptz,
    consecutive_failures smallint    NOT NULL DEFAULT 0
);

COMMENT ON COLUMN library_opac.fallback_url IS
    '반드시 채웁니다. 표준데이터의 홈페이지주소가 있으므로 링크가 없어 아무 데도 못 가는 '
    '경우는 발생하지 않습니다. 다만 어느 단계의 링크인지 화면에 정직하게 표시해야 합니다.';
COMMENT ON COLUMN library_opac.status IS
    'UNVERIFIABLE 은 자바스크립트로만 동작하거나 POST 만 받는 OPAC 입니다. '
    '헤드리스 브라우저를 만들지 않고 링크는 살려 둔 채 사용자 신고를 받습니다.';

CREATE TABLE link_check (
    check_id    bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lib_code    varchar(20) NOT NULL REFERENCES library ON DELETE CASCADE,
    checked_at  timestamptz NOT NULL DEFAULT now(),
    probe_kind  text        NOT NULL CHECK (probe_kind IN ('HEAD_BASE', 'GET_SEARCH_CANARY')),
    http_status integer,
    latency_ms  integer,
    final_url   text,
    result      text        NOT NULL,
    detail      text
);

CREATE INDEX link_check_lib_idx ON link_check (lib_code, checked_at DESC);

-- 어느 템플릿이 실제로 쓰이는지 알아야 점검 대상을 좁힐 수 있습니다.
CREATE TABLE click_log (
    lib_code   varchar(20) NOT NULL REFERENCES library ON DELETE CASCADE,
    work_id    integer,
    template_kind text,
    clicked_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX click_log_recent_idx ON click_log (clicked_at DESC);
CREATE INDEX click_log_lib_idx ON click_log (lib_code, clicked_at DESC);

