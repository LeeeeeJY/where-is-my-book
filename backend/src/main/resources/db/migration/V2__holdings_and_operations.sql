-- 소장 캐시와 운영 데이터.
--
-- 소장 관계를 미리 적재하지 않고 조회할 때 가져와 쌓는 설계입니다.
-- 근거는 docs/구현계획.md 3절과 8절에 있습니다.

-- ---------------------------------------------------------------
-- 소장 캐시
-- ---------------------------------------------------------------

CREATE TABLE holding_cache (
    isbn13      varchar(13) NOT NULL,
    region_code text        NOT NULL,
    lib_codes   text[]      NOT NULL,
    fetched_at  timestamptz NOT NULL DEFAULT now(),
    archive_key text,
    PRIMARY KEY (isbn13, region_code)
);

COMMENT ON TABLE holding_cache IS
    '버리는 데이터가 아니라 쌓이는 데이터입니다. 검색할 때마다 조회 결과가 누적되어 '
    '우리 소유의 소장 데이터가 되고, 쓸수록 빨라집니다.';
COMMENT ON COLUMN holding_cache.region_code IS
    '시도 코드. libSrchByBook 의 region 이 선택 항목이어서 전국을 한 번에 받으면 ALL 입니다.';
COMMENT ON COLUMN holding_cache.lib_codes IS
    'short_id 가 아니라 도서관부호로 저장합니다. 응답에 우리 마스터에 아직 없는 도서관이 '
    '나오더라도 값을 잃지 않고, 마스터를 갱신하면 그때부터 해석됩니다.';
COMMENT ON COLUMN holding_cache.fetched_at IS
    '만료시켜 버리지 않습니다. 오래된 항목도 이 시각과 함께 그대로 내보내고 배경에서 갱신합니다. '
    '화면에는 언제나 이 값을 표시해야 사용자가 "미소장"을 어떻게 읽을지 판단할 수 있습니다.';

-- 배경 갱신 대상을 고를 때 씁니다.
CREATE INDEX holding_cache_stale_idx ON holding_cache (fetched_at);
-- 특정 도서관이 나온 ISBN 을 찾을 때 씁니다. 링크 점검의 확인용 질의가 이걸 씁니다.
CREATE INDEX holding_cache_libs_idx ON holding_cache USING gin (lib_codes);

