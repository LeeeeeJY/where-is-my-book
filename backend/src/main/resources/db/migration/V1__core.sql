CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ---------------------------------------------------------------
-- 도서관 마스터
-- ---------------------------------------------------------------

CREATE TABLE library (
    lib_code        varchar(20) PRIMARY KEY,
    short_id        smallint    NOT NULL UNIQUE,
    name            text        NOT NULL,
    name_norm       text        NOT NULL,
    lib_type        text,
    sido            text        NOT NULL,
    sigungu         text        NOT NULL,
    address_road    text,
    latitude        double precision,
    longitude       double precision,
    homepage_url    text,
    phone           text,
    closed_days     text,
    open_hours      jsonb,
    d4l_lib_code    text,
    std_match_score real,
    std_match_state text        NOT NULL DEFAULT 'unmatched'
                                CHECK (std_match_state IN ('auto', 'manual', 'unmatched')),
    holdings_mode   text        NOT NULL DEFAULT 'api'
                                CHECK (holdings_mode IN ('api', 'bulk')),
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);

COMMENT ON COLUMN library.lib_code IS
    '국립중앙도서관 도서관부호. 모든 소스를 잇는 공통 키입니다.';
COMMENT ON COLUMN library.short_id IS
    '소장 조회와 URL 인코딩에 쓰는 내부 번호. 한 번 발급하면 절대 바꾸거나 재사용하지 않습니다. '
    '선택 상태가 이 번호로 URL에 담기므로, 값이 바뀌면 공유된 링크가 전부 조용히 깨집니다.';
COMMENT ON COLUMN library.std_match_state IS
    '전국도서관표준데이터와의 대조 상태. 표준데이터에는 도서관부호가 없어 이름과 주소로 '
    '대조해야 하고, 실패하면 위경도가 없어 "내 주변" 경로에 나타나지 않습니다. '
    'manual 은 사람이 확인한 것이므로 재실행해도 덮어쓰지 않습니다.';
COMMENT ON COLUMN library.holdings_mode IS
    '소장 정보를 얻는 방식. 지금은 전부 api 입니다. 자주 가는 도서관을 미리 적재해 '
    '즉시 응답하게 만들고 싶어지면 그 도서관만 bulk 로 바꿉니다.';
COMMENT ON COLUMN library.lib_type IS
    '관종. 표준데이터에는 작은도서관과 대학·전문도서관이 섞여 있으므로 '
    '선택 화면에서는 공공도서관만 걸러야 목록이 쓸 만해집니다.';

CREATE INDEX library_region_idx ON library (sido, sigungu);
CREATE INDEX library_type_idx ON library (lib_type);
CREATE INDEX library_name_norm_idx ON library USING gin (name_norm gin_trgm_ops);

-- 위경도에는 공간 색인을 걸지 않습니다. 1,604행짜리 테이블에서 전체 훑기가
-- 색인 조회보다 빠르고, cube/earthdistance 확장 의존이 하나 줄어듭니다.

-- short_id 는 바뀌면 안 됩니다. 규칙을 문서로만 두면 언젠가 반드시 어겨지므로
-- DB에서 막습니다.
CREATE FUNCTION library_short_id_is_immutable() RETURNS trigger AS $$
BEGIN
    IF NEW.short_id IS DISTINCT FROM OLD.short_id THEN
        RAISE EXCEPTION
            'short_id 는 변경할 수 없습니다 (도서관부호 %, % -> %). '
            '이 번호는 공유된 URL 에 들어 있어 값이 바뀌면 링크가 전부 깨집니다.',
            OLD.lib_code, OLD.short_id, NEW.short_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER library_short_id_immutable
    BEFORE UPDATE ON library
    FOR EACH ROW EXECUTE FUNCTION library_short_id_is_immutable();

-- 소스마다 자기 도서관 ID 체계를 쓰므로 도서관부호와 잇는 표를 따로 둡니다.
CREATE TABLE library_source_link (
    source_code  text        NOT NULL,
    source_key   text        NOT NULL,
    lib_code     varchar(20) NOT NULL REFERENCES library ON DELETE CASCADE,
    match_method text        NOT NULL
                             CHECK (match_method IN ('exact_name', 'name_addr', 'geo', 'manual')),
    match_score  real,
    confirmed    boolean     NOT NULL DEFAULT false,
    created_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (source_code, source_key)
);

COMMENT ON COLUMN library_source_link.confirmed IS
    '사람이 눈으로 확인한 연결. 대조를 다시 돌려도 이 행은 덮어쓰지 않습니다.';

CREATE INDEX library_source_link_lib_idx ON library_source_link (lib_code);

